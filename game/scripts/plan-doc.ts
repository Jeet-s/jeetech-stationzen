/// <reference types="node" />
/** Regenerate the per-level table at the end of docs/LEVELS.md from the level data (role, aha, why, mechanics). */
import { readFileSync, writeFileSync } from "fs";
import path from "path";
import { CHAPTERS, LEVELS } from "../src/game/levels";
import { mechanicsOf } from "../src/game/describe";

const file = path.join(__dirname, "../docs/LEVELS.md");
const doc = readFileSync(file, "utf8");
const head = doc.slice(0, doc.indexOf("## Levels"));
let out = head + "## Levels\n\nGenerated by `npx tsx scripts/plan-doc.ts` from `src/game/chapters/*.ts`. New = the mechanic first seen on that level.\n";
let n = 0;
const seen = new Set<string>();
CHAPTERS.forEach((c, ci) => {
  out += `\n### ${ci + 1}. ${c.name} — ${c.rule}\n\n| # | Level | Role | Aha (the insight) | Why here | New |\n|---|---|---|---|---|---|\n`;
  for (const spec of c.levels) {
    const L = LEVELS[n++];
    const fresh = mechanicsOf(L).filter((m) => !seen.has(m));
    fresh.forEach((m) => seen.add(m));
    const esc = (t: string) => t.replace(/\|/g, "\\|");
    out += `| ${n} | ${spec.name} | ${spec.role} | ${esc(spec.aha)} | ${esc(spec.why)} | ${fresh.join(", ")} |\n`;
  }
});
writeFileSync(file, out);
console.log(`docs/LEVELS.md: ${n} levels`);
